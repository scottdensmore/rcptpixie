// TestExtractPDFTextCorrupt is the guard against reintroducing the dslipak
// spin: a malformed PDF must return an error, never panic and never hang.
func TestExtractPDFTextCorrupt(t *testing.T) {
	dir := t.TempDir()
	good := buildPDF(t, filepath.Join(dir, "good.pdf"), []page{{lines: receiptLines}})
	raw, err := os.ReadFile(good)
	if err != nil {
		t.Fatal(err)
	}

	cases := map[string][]byte{
		"garbage":   []byte("%PDF-1.4\n" + strings.Repeat("\x00\xff\xfe not a pdf at all ", 200)),
		"truncated": raw[:len(raw)/2],
		"header":    []byte("this file is not a PDF at all\n"),
		"empty":     []byte("%PDF-1.4\n%%EOF\n"),
	}
	// Deterministic byte flips in the xref region.
	flipped := append([]byte(nil), raw...)
	for i, off := range []int{40, 55, 61, 70, 83, 97, 111, 130} {
		if p := len(flipped) - 1 - off; p > 8 {
			flipped[p] ^= byte(0x5a + i)
		}
	}
	cases["xref-flips"] = flipped

	for name, data := range cases {
		t.Run(name, func(t *testing.T) {
			path := filepath.Join(t.TempDir(), name+".pdf")
			if err := os.WriteFile(path, data, 0o644); err != nil {
				t.Fatal(err)
			}
			type result struct {
				text string
				err  error
			}
			done := make(chan result, 1)
			go func() {
				text, _, err := doc.ExtractPDFText(context.Background(), path, 3, nil)
				done <- result{text, err}
			}()
			select {
			case res := <-done:
				// A parser that returns no text and no error is acceptable: Load
				// sends that down the vision path. A hang or a panic is not.
				if res.err != nil && !errors.Is(res.err, doc.ErrPDFParse) {
					t.Fatalf("err = %v, want ErrPDFParse", res.err)
				}
				if res.err == nil && strings.TrimSpace(res.text) != "" {
					t.Fatalf("corrupt pdf yielded text: %q", res.text)
				}
			case <-time.After(10 * time.Second):
				t.Fatal("ExtractPDFText hung on a corrupt PDF")
			}
		})
	}
}

