func TestExtractPDFTextMultipage(t *testing.T) {
	path := buildPDF(t, filepath.Join(t.TempDir(), "multi.pdf"), []page{
		{lines: []string{"PAGE ONE MARKER"}},
		{lines: []string{"PAGE TWO MARKER"}},
		{lines: []string{"PAGE THREE MARKER"}},
	})

	text, pages, err := doc.ExtractPDFText(context.Background(), path, 3, nil)
	if err != nil {
		t.Fatalf("ExtractPDFText: %v", err)
	}
	if pages != 3 {
		t.Errorf("pages = %d, want 3", pages)
	}
	for _, want := range []string{"PAGE ONE MARKER", "PAGE TWO MARKER", "PAGE THREE MARKER"} {
		if !strings.Contains(text, want) {
			t.Errorf("text is missing %q:\n%s", want, text)
		}
	}

	// maxPages is a real bound, not advice.
	text, _, err = doc.ExtractPDFText(context.Background(), path, 1, nil)
	if err != nil {
		t.Fatalf("ExtractPDFText: %v", err)
	}
	if strings.Contains(text, "PAGE TWO MARKER") {
		t.Errorf("maxPages=1 read past page 1:\n%s", text)
	}
}

