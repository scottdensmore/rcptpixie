func scannedPDF(t *testing.T) string {
	t.Helper()
	return buildPDF(t, filepath.Join(t.TempDir(), "scanned.pdf"), []page{{}, {}})
}

func TestLoadScannedGoesToVision(t *testing.T) {
	path := scannedPDF(t)

	// With no rasterizer the user must be told what to install.
	_, err := doc.Load(context.Background(), path, nil, nil)
	if !errors.Is(err, doc.ErrNoRasterizer) {
		t.Fatalf("err = %v, want ErrNoRasterizer", err)
	}
	if !strings.Contains(err.Error(), "poppler") {
		t.Errorf("error does not name poppler: %v", err)
	}

	r := doc.Detect(nil)
	if r.Name() == "none" {
		t.Skip("no rasterizer on PATH")
	}
	d, err := doc.Load(context.Background(), path, r, nil)
	if err != nil {
		t.Fatalf("Load with %s: %v", r.Name(), err)
	}
	if d.Kind != doc.KindImages {
		t.Fatalf("Kind = %v, want KindImages", d.Kind)
	}
	if len(d.Images) == 0 || d.Pages != len(d.Images) {
		t.Fatalf("Images = %d, Pages = %d", len(d.Images), d.Pages)
	}
	for i, img := range d.Images {
		if strings.HasPrefix(img, "data:") {
			t.Fatalf("image %d carries a data: prefix", i)
		}
		raw, err := base64.StdEncoding.DecodeString(img)
		if err != nil {
			t.Fatalf("image %d is not bare base64: %v", i, err)
		}
		cfg, _, err := image.DecodeConfig(bytes.NewReader(raw))
		if err != nil {
			t.Fatalf("image %d does not decode: %v", i, err)
		}
		if cfg.Width <= 0 || cfg.Height <= 0 {
			t.Fatalf("image %d is %dx%d", i, cfg.Width, cfg.Height)
		}
	}
}

// TestLoadScannedFixtureReallyHasNoTextLayer keeps the vision path honest: a
// regenerated fixture that gained a text layer would leave it untested while
// every other test still passed.
func TestLoadScannedFixtureReallyHasNoTextLayer(t *testing.T) {
	assertNoTextLayer := func(t *testing.T, path string) {
		t.Helper()
		text, _, err := doc.ExtractPDFText(context.Background(), path, 3, nil)
		if err != nil {
			t.Fatalf("%s: %v", path, err)
		}
		n := 0
		for _, r := range text {
			if !unicode.IsSpace(r) {
				n++
			}
		}
		if n >= doc.MinTextChars {
			t.Errorf("%s has %d text runes, at or over MinTextChars %d: the vision path is no longer exercised",
				path, n, doc.MinTextChars)
		}
	}
	t.Run("synthetic", func(t *testing.T) { assertNoTextLayer(t, scannedPDF(t)) })
	t.Run("fixture", func(t *testing.T) { assertNoTextLayer(t, fixture(t, "receipt-scanned.pdf")) })
}

func writePNG(t *testing.T, path string, w, h int) string {
	t.Helper()
	img := image.NewRGBA(image.Rect(0, 0, w, h))
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			img.Set(x, y, color.RGBA{R: uint8(x), G: uint8(y), B: 0x40, A: 0xff})
		}
	}
	f, err := os.Create(path)
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	if err := png.Encode(f, img); err != nil {
		t.Fatal(err)
	}
	return path
}

func TestLoadImageIsBareBase64(t *testing.T) {
	paths := []string{writePNG(t, filepath.Join(t.TempDir(), "receipt.png"), 64, 48)}
	if _, err := os.Stat(filepath.Join("testdata", "receipt.jpg")); err == nil {
		paths = append(paths, filepath.Join("testdata", "receipt.jpg"))
	}

	for _, path := range paths {
		d, err := doc.Load(context.Background(), path, nil, nil)
		if err != nil {
			t.Fatalf("Load %s: %v", path, err)
		}
		if d.Kind != doc.KindImages {
			t.Errorf("%s Kind = %v, want KindImages", path, d.Kind)
		}
		if len(d.Images) != 1 || d.Pages != 1 {
			t.Fatalf("%s Images = %d, Pages = %d, want 1 and 1", path, len(d.Images), d.Pages)
		}
		if strings.HasPrefix(d.Images[0], "data:") {
			t.Errorf("%s carries a data: prefix", path)
		}
		raw, err := base64.StdEncoding.DecodeString(d.Images[0])
		if err != nil {
			t.Fatalf("%s is not bare base64: %v", path, err)
		}
		want, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(raw, want) {
			t.Errorf("%s: decoded bytes differ from the file", path)
		}
	}
}

