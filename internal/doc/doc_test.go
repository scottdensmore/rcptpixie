const omissionSignature = " characters omitted ...]"

func TestTruncate(t *testing.T) {
	sizes := []int{0, 1, 63, 100, 101, 999, 1000, 5000, 12000, 12001, 50000}
	limits := []int{100, 1000, 12000}

	for _, size := range sizes {
		s := syntheticText(size)
		for _, limit := range limits {
			out, truncated := doc.Truncate(s, limit)
			if len(out) > limit {
				t.Errorf("size %d limit %d: len(out) = %d, over the limit", size, limit, len(out))
			}
			if !utf8.ValidString(out) {
				t.Errorf("size %d limit %d: output is not valid UTF-8", size, limit)
			}
			if truncated != (len(s) > limit) {
				t.Errorf("size %d limit %d: truncated = %v", size, limit, truncated)
			}
			if !truncated {
				if out != s {
					t.Errorf("size %d limit %d: untruncated output differs from the input", size, limit)
				}
				continue
			}
			if n := strings.Count(out, omissionSignature); n != 1 {
				t.Fatalf("size %d limit %d: omission marker appears %d times", size, limit, n)
			}
			_, tail, _ := strings.Cut(out, omissionSignature)
			tail = strings.TrimPrefix(tail, "\n")
			if tail == "" || !strings.HasSuffix(s, tail) {
				t.Fatalf("size %d limit %d: the tail of the input did not survive (kept %d bytes)", size, limit, len(tail))
			}
			// The TOTAL lives in the last lines; losing it defeats the tool.
			if limit >= 1000 && len(tail) < 200 {
				t.Errorf("size %d limit %d: only %d trailing bytes kept, want >= 200", size, limit, len(tail))
			}
		}
	}
}

func TestTruncateInvalidUTF8(t *testing.T) {
	s := strings.Repeat("caf\xc3", 4000) // truncated é bytes throughout
	out, _ := doc.Truncate(s, 1000)
	if !utf8.ValidString(out) {
		t.Fatal("output is not valid UTF-8")
	}
	if len(out) > 1000 {
		t.Fatalf("len(out) = %d, over the limit", len(out))
	}
}

// syntheticText builds n bytes of receipt-shaped, valid UTF-8 text ending in a
// recognisable total line.
func syntheticText(n int) string {
	if n == 0 {
		return ""
	}
	var b strings.Builder
	line := 0
	for b.Len() < n {
		fmt.Fprintf(&b, "%04d Café Ünïcode item — 12.34\n", line)
		line++
	}
	s := b.String()[:n]
	// Keep the result valid UTF-8 after the hard cut.
	for len(s) > 0 && !utf8.ValidString(s) {
		s = s[:len(s)-1]
	}
	return s
}
