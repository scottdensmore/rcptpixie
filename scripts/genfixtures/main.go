const outDir = "../../testdata"

// errSkip marks a fixture that cannot be produced on this machine.
var errSkip = errors.New("skipped")

var receiptLines = []string{
	"123 Main Street",
	"Springfield, IL 62704",
	"",
	"Date: 2023-01-15",
	"Invoice: 4471",
	"",
	"1x Coffee                4.50",
	"1x Sandwich              9.95",
	"1x Catering            99.00",
	"",
	"Subtotal              113.45",
	"Tax                    10.00",
	"Total: $123.45",
}

func main() {
	fixtures := []struct {
		name string
		fn   func() error
	}{
		{"receipt-text.pdf", writeTextPDF},
		{"receipt-multipage.pdf", writeMultipagePDF},
		{"receipt-encrypted.pdf", writeEncryptedPDF},
		{"receipt-corrupt.pdf", writeCorruptPDF},
		{"receipt-empty.pdf", writeEmptyPDF},
		{"receipt.png", writePNG},
		{"receipt.jpg", writeJPG},
		{"receipt-scanned.pdf", writeScannedPDF},
	}

	if err := os.MkdirAll(outDir, 0o755); err != nil {
		fmt.Fprintln(os.Stderr, "genfixtures:", err)
		os.Exit(1)
	}
	failed := false
	for _, f := range fixtures {
		switch err := f.fn(); {
		case errors.Is(err, errSkip):
			fmt.Printf("skip  %s: %v\n", f.name, err)
		case err != nil:
			fmt.Fprintf(os.Stderr, "error %s: %v\n", f.name, err)
			failed = true
		default:
			fmt.Printf("wrote %s\n", filepath.Join(outDir, f.name))
		}
	}
	if failed {
		os.Exit(1)
	}
}

func out(name string) string { return filepath.Join(outDir, name) }

// fixedDate keeps regenerated fixtures byte-identical; gofpdf otherwise stamps
// the current time and every rerun shows up as a diff.
var fixedDate = time.Date(2023, 1, 15, 12, 0, 0, 0, time.UTC)

func newPDF() *gofpdf.Fpdf {
	pdf := gofpdf.New("P", "pt", "Letter", "")
	pdf.SetCreationDate(fixedDate)
	pdf.SetModificationDate(fixedDate)
	return pdf
}

func newReceipt() *gofpdf.Fpdf {
	pdf := newPDF()
	pdf.SetTitle("Test Store Receipt", false)
	return pdf
}

func receiptPage(pdf *gofpdf.Fpdf, heading string, lines []string) {
	pdf.AddPage()
	pdf.SetFont("Helvetica", "B", 18)
	pdf.SetXY(56, 56)
	pdf.Cell(300, 22, heading)
	pdf.SetFont("Courier", "", 12)
	y := 96.0
	for _, line := range lines {
		pdf.SetXY(56, y)
		pdf.Cell(400, 16, line)
		y += 18
	}
}

func writeTextPDF() error {
	pdf := newReceipt()
	receiptPage(pdf, "Test Store", receiptLines)
	return pdf.OutputFileAndClose(out("receipt-text.pdf"))
}

func writeMultipagePDF() error {
	pdf := newReceipt()
	receiptPage(pdf, "Test Store", receiptLines)
	receiptPage(pdf, "Test Store - Page 2", []string{
		"Itemized detail continued",
		"2x Napkins               0.50",
		"1x Delivery              6.00",
	})
	receiptPage(pdf, "Test Store - Page 3", []string{
		"Payment: Visa ending 4242",
		"Authorization: 00931A",
		"Thank you for your business",
	})
	return pdf.OutputFileAndClose(out("receipt-multipage.pdf"))
}

func writeEncryptedPDF() error {
	pdf := newReceipt()
	pdf.SetProtection(gofpdf.CnProtectPrint, "userpw", "ownerpw")
	receiptPage(pdf, "Test Store", receiptLines)
	return pdf.OutputFileAndClose(out("receipt-encrypted.pdf"))
}

// writeCorruptPDF flips a fixed set of bytes in the cross-reference region of
// receipt-text.pdf. The seed is fixed so the fixture is reproducible.
func writeCorruptPDF() error {
	data, err := os.ReadFile(out("receipt-text.pdf"))
	if err != nil {
		return err
	}
	start := bytes.LastIndex(data, []byte("\nxref"))
	if start < 0 {
		return errors.New("no xref table in receipt-text.pdf")
	}
	rng := rand.New(rand.NewSource(20230115))
	region := data[start:]
	for i := 0; i < 8; i++ {
		region[rng.Intn(len(region))] ^= 0x5a
	}
	return os.WriteFile(out("receipt-corrupt.pdf"), data, 0o644)
}

func writeEmptyPDF() error {
	return os.WriteFile(out("receipt-empty.pdf"), []byte("%PDF-1.4\n%%EOF\n"), 0o644)
}

// writeScannedPDF rasterizes receipt-text.pdf and re-embeds the bitmap, so the
// result has a page but no text layer at all.
func writeScannedPDF() error {
	if _, err := exec.LookPath("pdftoppm"); err != nil {
		return fmt.Errorf("%w: pdftoppm not on PATH (install poppler-utils)", errSkip)
	}
	dir, err := os.MkdirTemp("", "genfixtures")
	if err != nil {
		return err
	}
	defer os.RemoveAll(dir)

	prefix := filepath.Join(dir, "page")
	cmd := exec.Command("pdftoppm", "-png", "-r", "150", "-f", "1", "-l", "1", "-singlefile",
		out("receipt-text.pdf"), prefix)
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("pdftoppm: %w", err)
	}

	pdf := newPDF()
	pdf.AddPage()
	w, h := pdf.GetPageSize()
	opt := gofpdf.ImageOptions{ImageType: "PNG"}
	pdf.ImageOptions(prefix+".png", 0, 0, w, h, false, opt, 0, "")
	if err := pdf.Error(); err != nil {
		return err
	}
	return pdf.OutputFileAndClose(out("receipt-scanned.pdf"))
}

func writePNG() error {
	f, err := os.Create(out("receipt.png"))
	if err != nil {
		return err
	}
	defer f.Close()
	return png.Encode(f, receiptImage())
}

func writeJPG() error {
	f, err := os.Create(out("receipt.jpg"))
	if err != nil {
		return err
	}
	defer f.Close()
	return jpeg.Encode(f, receiptImage(), &jpeg.Options{Quality: 90})
}

// receiptImage draws the same receipt with the built-in bitmap font below, so
// the fixture is legible to a vision model without pulling in a font package.
func receiptImage() image.Image {
	const (
		w, h   = 640, 440
		scale  = 3
		margin = 24
	)
	img := image.NewGray(image.Rect(0, 0, w, h))
	for i := range img.Pix {
		img.Pix[i] = 0xff
	}
	lines := append([]string{"TEST STORE"}, receiptLines...)
	y := margin
	for _, line := range lines {
		drawText(img, margin, y, line, scale)
		y += 9 * scale
	}
	return img
}

func drawText(img *image.Gray, x, y int, s string, scale int) {
	for _, r := range s {
		glyph, ok := font[r]
		if !ok {
			glyph = font['?']
		}
		for row := 0; row < 7; row++ {
			for col := 0; col < 5; col++ {
				if glyph[row]&(1<<(4-col)) == 0 {
					continue
				}
				for dy := 0; dy < scale; dy++ {
					for dx := 0; dx < scale; dx++ {
						px, py := x+col*scale+dx, y+row*scale+dy
						if image.Pt(px, py).In(img.Rect) {
							img.Pix[img.PixOffset(px, py)] = 0x00
						}
					}
				}
			}
		}
		x += 6 * scale
	}
}

